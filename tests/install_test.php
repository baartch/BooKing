foreach ($statements as $statement) {
    if (preg_match('/CREATE TABLE/i', $statement)) {
        $createInStatements++;
    }
}
check(
    $createInStatements === count($createMatches[0]),
    'Every CREATE TABLE kept as its own statement (' . $createInStatements . ')'
);

$miniSql = "-- leading comment\nCREATE TABLE a (x INT);\n\n-- middle comment\nCREATE TABLE b (y INT);\nINSERT INTO a VALUES (1); -- trailing comment\nCREATE TABLE c (z INT)";
$miniStatements = splitSqlStatements($miniSql);
check(count($miniStatements) === 4, 'Mini SQL splits into 4 statements (' . count($miniStatements) . ')');
