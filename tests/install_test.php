$claimA2 = claimInstallerLock('session-hash-a', $lockPath);
check($claimA2['ok'] === true, 'Original session can resume');

$lock = $claimA2['lock'];
$lock['step'] = 'admin';
$lock['config_written'] = true;
check(saveInstallerLock($lock, $lockPath) === true, 'Lock progress can be saved');
$fetched = fetchInstallerLock($lockPath);
check($fetched['step'] === 'admin' && $fetched['config_written'] === true, 'Saved progress is read back');

check(completeInstallerLock($lockPath) === true, 'Lock can be completed');
$fetched = fetchInstallerLock($lockPath);
check($fetched['state'] === 'completed', 'Completed lock has completed state');

$claimAfter = claimInstallerLock('session-hash-a', $lockPath);
check($claimAfter['ok'] === false && $claimAfter['error'] === 'completed', 'Completed lock refuses original session');
$claimBAfter = claimInstallerLock('session-hash-b', $lockPath);
check($claimBAfter['ok'] === false && $claimBAfter['error'] === 'completed', 'Completed lock refuses any session');

