// --- lock lifecycle ---------------------------------------------------------
echo "\nTest group: installer lock lifecycle\n";
$base = tempBaseDir('lock');
$lockPath = $base . '/config/installer.lock';

$claimA = claimInstallerLock('session-hash-a', $lockPath);
