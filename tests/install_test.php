echo "\nTest group: SQL statement splitting\n";
$schemaSql = (string) file_get_contents(__DIR__ . '/../sql/schema.sql');
$statements = splitSqlStatements($schemaSql);
check(count($statements) > 20, 'Schema splits into more than 20 statements (' . count($statements) . ')');
check(trim($statements[0]) !== '' && trim($statements[count($statements) - 1]) !== '', 'No empty statements');
$commentRemains = false;
foreach ($statements as $statement) {
    if (preg_match('/(^|\n)\s*--/', $statement)) {
        $commentRemains = true;
        break;
    }
}
check(!$commentRemains, 'Comments stripped from statements');
preg_match_all('/CREATE TABLE/i', $schemaSql, $createMatches);
